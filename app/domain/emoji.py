"""Запрет эмодзи и смайликов в сообщениях чата: проверка входящего текста и зачистка ответов модели."""

import re

EMOJI_RE = re.compile(
    "["
    "\U0001f000-\U0001faff"  # пиктограммы, эмоции, транспорт, флаги (региональные индикаторы), карты
    "☀-➿"  # разные символы и dingbats: ☀ ☎ ✔ ✨ ❤
    "⬀-⯿"  # стрелки и фигуры: ⭐ ⬆ ⬛
    "⌚⌛⏩-⏳⏸-⏺"  # часы, ⏩ ⏰ (без клавиш Mac ⌘ ⌥ ⏎)
    "‼⁉▪▫▶◀◻-◾⤴⤵〰〽㊗㊙"
    "️‍⃣"  # селектор эмодзи, склейка, рамка клавиши
    "]"
    # текстовые смайлики: :) :-( ;) =D :P и «)))»; «12:30)» и «http://» не задеваются
    r"|[:;=][-^']?[()DPpOo](?!\w)"
    r"|\){3,}"
)
EMOJI_FORBIDDEN_MESSAGE = "Эмодзи и смайлики в чате не поддерживаются: уберите их из сообщения."


def has_emoji(text: str) -> bool:
    """Проверяет, есть ли в тексте эмодзи или текстовые смайлики.

    Args:
        text: Проверяемый текст.

    Returns:
        True, если найден хотя бы один эмодзи или смайлик.
    """
    return EMOJI_RE.search(text) is not None


def strip_emoji(text: str) -> str:
    """Удаляет из текста эмодзи и смайлики, не трогая остальное форматирование.

    Args:
        text: Ответ или подсказка модели.

    Returns:
        Исходный текст, если смайлов нет; иначе текст без них, без двойных пробелов и пробелов перед знаками
        препинания на месте удалённого.
    """
    if not has_emoji(text):
        return text
    cleaned = EMOJI_RE.sub("", text)
    cleaned = re.sub(r"[ \t]{2,}", " ", cleaned)
    cleaned = re.sub(r"[ \t]+([.,;!?])", r"\1", cleaned)
    return re.sub(r"[ \t]+$", "", cleaned, flags=re.MULTILINE).strip()
